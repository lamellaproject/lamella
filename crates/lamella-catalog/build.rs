//! Embeds the board and part fact files into the `lamella` binary.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

fn main() {
    let repo = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"))
        .join("..")
        .join("..");
    let board_dirs = lamella_bsp_gen::boards::board_dirs(&repo).unwrap_or_else(|error| panic!("{error}"));
    let boards = collect(&board_dirs, Path::new("board.toml"));
    let parts = collect(&subdirectories(&repo.join("csp")), Path::new("parts.toml"));
    let modules = collect(&subdirectories(&repo.join("csp")), Path::new("module.toml"));
    let board_python = collect(&board_dirs, &Path::new("python").join("board.py"));
    let bus_tables = collect(&board_dirs, &Path::new("rust").join("bus_table.rs"));

    println!("cargo:rerun-if-changed={}", repo.join(lamella_bsp_gen::boards::BOARDS_DIR).display());
    println!("cargo:rerun-if-changed={}", repo.join("csp").display());
    for path in boards
        .values()
        .chain(parts.values())
        .chain(modules.values())
        .chain(board_python.values())
        .chain(bus_tables.values())
    {
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let mut out = String::from(
        "// Generated by `build.rs` from `bsp/` and `csp/`. Do not edit.\n\n\
         /// Every board's `board.toml`, by board id.\n\
         pub const BOARDS: &[(&str, &str)] = &[\n",
    );
    for (id, path) in &boards {
        out.push_str(&format!("    ({id:?}, include_str!({:?})),\n", path.display().to_string()));
    }
    out.push_str("];\n\n/// Every family's `parts.toml`, by family id.\npub const PARTS: &[(&str, &str)] = &[\n");
    for (id, path) in &parts {
        out.push_str(&format!("    ({id:?}, include_str!({:?})),\n", path.display().to_string()));
    }
    out.push_str(
        "];\n\n/// Every module's `module.toml`, by module id -- the hop from a module-carrying \
         board to the family and part it holds.\npub const MODULES: &[(&str, &str)] = &[\n",
    );
    for (id, path) in &modules {
        out.push_str(&format!("    ({id:?}, include_str!({:?})),\n", path.display().to_string()));
    }
    out.push_str(
        "];\n\n/// Every board's GENERATED Python `board` module, by board id -- what `import \
         board` serves\n/// when a program is run against a named board.\npub const BOARD_PYTHON: \
         &[(&str, &str)] = &[\n",
    );
    for (id, path) in &board_python {
        out.push_str(&format!("    ({id:?}, include_str!({:?})),\n", path.display().to_string()));
    }
    out.push_str(
        "];\n\n/// Every board's GENERATED bus table, by board id: the words the host writes into an image \
         built\n/// for that board. A board whose family has no table has no entry.\npub const BUS_TABLES: \
         &[(&str, &[u32])] = &[\n",
    );
    for (index, id) in bus_tables.keys().enumerate() {
        out.push_str(&format!("    ({id:?}, bus_tables::board_{index}::BUS_TABLE),\n"));
    }
    out.push_str("];\n\nmod bus_tables {\n");
    for (index, path) in bus_tables.values().enumerate() {
        out.push_str(&format!("    #[path = {:?}]\n    pub mod board_{index};\n", path.display().to_string()));
    }
    out.push_str("}\n");

    let dest = PathBuf::from(std::env::var_os("OUT_DIR").expect("out dir")).join("catalog.rs");
    std::fs::write(&dest, out).expect("write catalog");
}

/// Every one of `dirs` containing `file`, as `id -> path` where the id is the directory's name,
/// sorted by id so the generated table is stable across builds (an unstable order is a diff on every
/// rebuild).
///
/// `file` is a path RELATIVE to each directory, so a fact stated one level down
/// (`<board>/python/board.py`) is collected by the same walk as one stated at the top.
fn collect(dirs: &[PathBuf], file: &Path) -> BTreeMap<String, PathBuf> {
    let mut found = BTreeMap::new();
    for dir in dirs {
        let candidate = dir.join(file);
        if candidate.is_file()
            && let Some(id) = dir.file_name().and_then(|name| name.to_str())
        {
            found.insert(id.to_string(), candidate);
        }
    }
    found
}

/// Every immediate subdirectory of `root`, or none when `root` cannot be read.
fn subdirectories(root: &Path) -> Vec<PathBuf> {
    let Ok(entries) = std::fs::read_dir(root) else {
        return Vec::new();
    };
    entries.flatten().map(|entry| entry.path()).collect()
}
