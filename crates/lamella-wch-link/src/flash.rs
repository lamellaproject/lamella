//! Chip-specific flash parameters for the WCH-LinkE native fast-program flow.

/// The per-chip inputs to the WCH-LinkE fast-program flow. Extend with a new `const` per supported
/// family; the flow in [`WchLink::flash`](crate::WchLink::flash) is family-agnostic given these.
#[derive(Clone, Copy, Debug)]
pub struct ChipFlash {
    /// The chip-family selector byte (`riscvchip`) the probe expects in `set-speed`/`attach` -- e.g.
    /// `0x09` for the CH32V003 family. It selects the probe's per-family programming behavior.
    pub riscvchip: u8,
    /// The RAM flash-loader the probe writes into target SRAM before streaming the image; the probe
    /// then drives this loader to program flash. Family-specific machine code.
    pub flash_op: &'static [u8],
    /// The USB bulk data-endpoint packet size (bytes). The flash-op and the image stream go out in
    /// packets of exactly this length, the final short packet padded with `0xff`.
    pub data_packet_size: usize,
    /// The fast-program pack size (bytes): the image is streamed one pack at a time, each pack followed
    /// by a one-word probe acknowledgement.
    pub write_pack_size: usize,
    /// Where the chip maps code flash. The default flash address when a caller does not specify one;
    /// the image is position-independent, so the exact base is immaterial to a `.bin` linked at `0`.
    pub code_flash_start: u32,
}

/// The CH32V003 family (QingKe RV32EC, `riscvchip` `0x09`): 64-byte data packets, 1 KiB fast-program
/// packs, code flash at `0x0800_0000`, and the 498-byte CH32V003 RAM flash-loader. Also covers the
/// CH641 (same loader and parameters in wlink's map).
pub const CH32V003: ChipFlash = ChipFlash {
    riscvchip: 0x09,
    flash_op: &CH32V003_FLASH_OP,
    data_packet_size: 64,
    write_pack_size: 1024,
    code_flash_start: 0x0800_0000,
};

