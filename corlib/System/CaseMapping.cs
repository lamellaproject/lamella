        internal static char ToUpper(char c)
        {
            if (c < 0x80)
            {
                if (c >= 'a' && c <= 'z') return (char)(c - 32);
                return c;
            }
            return (char)Map(UpperBmp, c);
        }

        internal static char ToLower(char c)
        {
            if (c < 0x80)
            {
                if (c >= 'A' && c <= 'Z') return (char)(c + 32);
                return c;
            }
            return (char)Map(LowerBmp, c);
        }

        internal static int ToUpperCodePoint(int cp)
        {
            if (cp <= 0xFFFF) return cp < 0x80 ? (int)ToUpper((char)cp) : Map(UpperBmp, cp);
            if (cp <= 0x1FFFF) return 0x10000 + Map(UpperSupplementary, cp - 0x10000);
            return cp;
        }

        internal static int ToLowerCodePoint(int cp)
        {
            if (cp <= 0xFFFF) return cp < 0x80 ? (int)ToLower((char)cp) : Map(LowerBmp, cp);
            if (cp <= 0x1FFFF) return 0x10000 + Map(LowerSupplementary, cp - 0x10000);
            return cp;
        }

        private static int Map(string records, int cp)
        {
            int lo = 0;
            int hi = records.Length / 3 - 1;
            while (lo <= hi)
            {
                int mid = (lo + hi) / 2;
                int at = mid * 3;
                int start = records[at];
                int countStride = records[at + 1];
                int stride = (countStride & 0x8000) != 0 ? 2 : 1;
                int end = start + ((countStride & 0x7FFF) - 1) * stride;
                if (cp < start) hi = mid - 1;
                else if (cp > end) lo = mid + 1;
                else
                {
                    if (stride == 2 && ((cp - start) & 1) != 0) return cp;
                    return (cp + records[at + 2]) & 0xFFFF;
                }
            }
            return cp;
        }
